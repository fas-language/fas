open Fas_linker

let usage =
  "Usage: fas-ld [OPTIONS] OBJECT_OR_ARCHIVE...\n\
   Linux x86-64 ELF linker.\n\
   -o, --output PATH        output executable (default: a.out)\n\
   -e, --entry SYMBOL       entry point (default: _start)\n\
   -r, --relocatable        combine inputs into a relocatable ELF object\n\
   -L DIR, -LDIR            library search directory\n\
   --sysroot DIR           root for =/$SYSROOT search and script paths\n\
   --library-path DIR      long form of -L (also --library-path=DIR)\n\
   -l NAME, -lNAME          search libraries (-l:FILE for exact name)\n\
   --start-group/--end-group rescan archives to resolve cycles\n\
   --whole-archive          include every member of following archives\n\
   --no-whole-archive       return to lazy archive extraction\n\
   --as-needed/--no-as-needed conditional following shared dependencies\n\
   --push-state/--pop-state save/restore dependency selection policy\n\
   -Bstatic/-Bdynamic      select archive-only / shared-first library search\n\
   -static                 static output and archive-only library search\n\
   -static-pie             static PIE with CRT-owned self-relocation\n\
   --no-dynamic-linker     omit interpreter (with -pie, select static PIE)\n\
   @FILE                   read arguments from a quoted response file\n\
   --stats                 write timing/allocation statistics as JSON to stderr\n\
   -Map PATH               write a deterministic section/symbol map\n\
   --gc-sections           discard unreachable allocatable sections\n\
   --no-gc-sections        retain allocatable sections (default)\n\
   -u SYMBOL               archive extraction and section-GC root\n\
   -pie / -no-pie          enable/disable loader-backed PIE output\n\
   -shared                 emit a shared library (entry address zero)\n\
   -soname NAME            runtime shared-library identity\n\
   --version-script PATH   bounded export/version policy for a shared library\n\
   --no-undefined          reject unresolved strong shared-library references\n\
   --allow-multiple-definition, -z muldefs  keep the first strong definition\n\
   -z relro/norelro        enable/disable RELRO (dynamic default: enabled)\n\
   -z now/defs/undefs      eager binding / strict / permissive undefined policy\n\
   --dynamic-linker PATH   program interpreter (PIE default: glibc x86-64)\n\
   -rpath PATH             runtime library search path ($ORIGIN preserved)\n\
   --enable-new-dtags      emit RUNPATH (default); --disable-new-dtags: RPATH\n\
   --no-allow-shlib-undefined validate transitive DSO dependencies and references\n\
   -rpath-link PATH        explicit search paths for strict DSO validation\n\
   -E, --export-dynamic    export visible executable definitions\n\
   --no-export-dynamic     export only definitions referenced by DSOs\n\
   --hash-style=sysv/gnu/both dynamic symbol lookup tables (default: sysv)\n\
   --build-id[=sha1/md5/none] deterministic GNU build identifier\n\
   -m elf_x86_64           explicit target emulation\n\
   --eh-frame-hdr          accepted; unwind indexes are generated by default\n\
   -nostdlib               ignore script SEARCH_DIR paths; retain explicit -L\n\
   --                      end options\n\
   --help                  show this help\n\
   --version               show version\n"

let run () =
  match Command_line.parse (Array.to_list Sys.argv |> List.tl) with
  | Help -> print_string usage
  | Version -> print_endline "fas-ld 0.7-dev (ELF64 x86-64 Linux compatibility work)"
  | Link config ->
      let stats = if config.statistics then Some (Stats.create ()) else None in
      Fun.protect
        (fun () ->
          if config.relocatable then
            Partial_link.link_input_files ?stats ~options:config.options
              ~output:config.output config.inputs
          else
            Static_link.link_input_files ?stats ~options:config.options
              ~entry:config.entry ?map_file:config.map_file ~output:config.output
              config.inputs)
        ~finally:(fun () ->
          Option.iter (fun stats -> prerr_endline (Stats.json stats)) stats)

let () =
  try Error.io run
  with Error.Error message ->
    prerr_endline ("fas-ld: " ^ message);
    exit 1
