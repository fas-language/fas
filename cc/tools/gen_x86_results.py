#!/usr/bin/env python3
"""Generate GCC x86 intrinsic result types from gcc/config/i386 in GCC 15.2."""
import re
import sys
from pathlib import Path

SCALAR = {}
for name, aliases in {
    'VOID': 'VOID', 'CHAR': 'CHAR QI', 'UCHAR': 'UCHAR UQI UINT8',
    'SHORT': 'SHORT HI', 'USHORT': 'USHORT UHI UINT16',
    'INT': 'INT SI', 'UINT': 'UINT UNSIGNED USI',
    'ULONG': 'ULONG', 'LLONG': 'DI INT64 LONGLONG',
    'ULLONG': 'UDI UINT64 ULONGLONG',
    'FLOAT16': 'FLOAT16', 'FLOAT': 'FLOAT', 'DOUBLE': 'DOUBLE',
    'LDOUBLE': 'FLOAT80', 'BFLOAT16': 'BFLOAT16',
}.items():
    SCALAR.update((alias, 'TY_' + name) for alias in aliases.split())


def generate(source):
    descriptions = (source / 'i386-builtin.def').read_text()
    registration = (source / 'i386-builtins.cc').read_text()
    aliases = (source / 'i386-builtins.h').read_text()
    types = (source / 'i386-builtin-types.def').read_text()
    vectors = dict(re.findall(r'^DEF_VECTOR_TYPE \((\w+), (\w+)', types, re.M))
    results = {}
    functions = dict(re.findall(r'^#define\s+(\w+)\s+(\w+)_FTYPE\w+', aliases, re.M))
    for name, result in re.findall(
            r'"__builtin_ia32_(\w+)"[^")]*?,\s*(?:\(int\)\s*)?(\w+)_FTYPE\w+', descriptions):
        results[name] = result
    for name, signature in re.findall(
            r'"__builtin_ia32_(\w+)"[^\n]*?,[ \t]*(?:\(int\)[ \t]*)?(\w+)[ \t]*\)', descriptions):
        if signature in functions:
            results[name] = functions[signature]
    for name, result in re.findall(
            r'"__builtin_ia32_(\w+)"\s*,\s*(\w+)_FTYPE\w+', registration):
        results[name] = result
    results.update(pcmpistrm128='V16QI', pcmpestrm128='V16QI')
    # A zero result code is reserved for the generic builtin fallback. Omit
    # result types that the front end does not yet represent.
    encoded = {}
    for name, result in results.items():
        if result in SCALAR:
            encoded[name] = SCALAR[result]
        elif result == 'PVOID':
            encoded[name] = '256 + TY_VOID'
        elif result in vectors and vectors[result] in SCALAR:
            lanes = int(re.match(r'V(\d+)', result)[1])
            encoded[name] = f'{512 * lanes} + {SCALAR[vectors[result]]}'
    if len(encoded) < 1500 or encoded.get('slwpcb') != '256 + TY_VOID':
        raise ValueError('incomplete GCC x86 signature data')
    names = sorted(encoded)
    print('// Generated by cc/tools/gen_x86_results.py from GCC 15.2 type information.')
    print(f'const X86_RESULT_COUNT usize = {len(names)}')
    print('const X86_RESULT_NAMES arr[X86_RESULT_COUNT, addr] = {')
    for name in names:
        print(f'    c"{name}",')
    print('}')
    print('const X86_RESULT_TYPES arr[X86_RESULT_COUNT, u32] = {')
    for i in range(0, len(names), 6):
        print('    ' + ', '.join(encoded[name] for name in names[i:i + 6]) + ',')
    print('}')


if __name__ == '__main__':
    generate(Path(sys.argv[1]))
