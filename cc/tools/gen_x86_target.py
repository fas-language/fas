#!/usr/bin/env python3
"""Extract fcc's supported x86 driver feature and CPU macro tables from Clang 22."""

import re
import subprocess
import sys

FLAGS = """
mmx fxsr sse sse2 sse3 ssse3 sse4.1 sse4.2 sse4a avx avx2 avx512f avx512cd
avx512dq avx512bw avx512vl avx512vbmi avx512vbmi2 avx512vnni avx512ifma
avx512bitalg avx512vpopcntdq avx512bf16 avx512fp16 avxvnni aes pclmul sha
sha512 vaes vpclmulqdq gfni popcnt bmi bmi2 lzcnt adx f16c fma fma4 xop movbe
rdrnd rdseed cx16 crc32 clflushopt clwb clzero fsgsbase xsave xsavec xsaveopt
xsaves rtm tbm mwaitx
""".split()
CLANG = sys.argv[1] if len(sys.argv) > 1 else "clang-22"
CPU_BASE = "-march=x86-64"

def clang(*args):
    return subprocess.run([CLANG, "--target=x86_64-linux-gnu", *args],
                          text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)

def macros(*args):
    p = clang("-std=gnu23", "-dM", "-E", "-x", "c", *args, "/dev/null")
    if p.returncode:
        return None
    return dict(re.findall(r"^#define (\S+) (.+)$", p.stdout, re.M))

def fas_string(s):
    return 'c"' + s.replace("\n", r"\n") + '"'

def generate():
    cpus = re.findall(r"^\s+([a-zA-Z0-9_+.-]+)\s*$",
                      clang("--print-supported-cpus").stderr, re.M)
    cpu_macros = {cpu: m for cpu in cpus if (m := macros("-march=" + cpu)) is not None}
    default = macros(CPU_BASE)
    minimal = macros(CPU_BASE, "-mno-mmx", "-mno-sse", "-mno-fxsr")
    on = {flag: macros(CPU_BASE, "-mno-mmx", "-mno-sse", "-mno-fxsr", "-m" + flag)
          for flag in FLAGS}
    for flag, m in on.items():
        if m is None:
            raise ValueError(f"Clang does not accept -m{flag}")
    # Clang spells several dependent macros differently from the command-line
    # feature (e.g. SSE4_2, PCLMUL and legacy __SSE_MATH__).
    controlled = sorted(set(default).difference(minimal) |
                        set().union(*(set(m).difference(minimal) for m in on.values())))
    half = [name for name in controlled if name.startswith("__FLT16_")]
    controlled = [name for name in controlled if name not in half]
    assert len(controlled) <= 64, controlled
    def mask(names):
        return sum(1 << i for i, macro in enumerate(controlled) if macro in names)
    profiles = ["x86-64-v4", "znver5", "clearwaterforest", "pantherlake", "bdver4"]
    print("// Generated by cc/tools/gen_x86_target.py using clang-22.")
    print(f"const X86_MACRO_COUNT usize = {len(controlled)}")
    print(f"const X86_MACROS arr[{len(controlled)}, addr] = {{")
    for name in controlled:
        names = [name] + (half if name == "__SSE2__" else [])
        definitions = "".join(f"{item} {default.get(item, '1')}\n" for item in names)
        print(f"    {fas_string(definitions)},")
    print("}")
    # Most flags have transitive dependencies. Observe their removals against
    # multiple CPU families to cover both Intel and AMD extensions.
    print(f"const X86_FLAG_COUNT usize = {len(FLAGS)}")
    print(f"const X86_FLAGS arr[{len(FLAGS)}, X86Flag] = {{")
    for flag, m in on.items():
        disabled = set()
        for cpu in profiles:
            before = set(cpu_macros[cpu])
            after = macros("-march=" + cpu, "-mno-" + flag)
            disabled.update(before.difference(after))
        enabled = set(m).difference(minimal)
        own = "__" + flag.upper().replace(".", "_") + "__"
        if flag == "cx16":
            own = "__GCC_HAVE_SYNC_COMPARE_AND_SWAP_16"
        assert own in controlled, (flag, own)
        print(f'    {{ c"{flag}", {mask(enabled):#x}, {mask(disabled | {own}):#x}, {mask([own]):#x} }},')
    print("}")
    print(f"const X86_CPU_COUNT usize = {len(cpu_macros) + 1}")
    print(f"const X86_CPUS arr[{len(cpu_macros) + 1}, X86Cpu] = {{")
    # No -march option uses the legacy k8 CPU names on Linux.
    old_names = "__k8 1\n__k8__ 1\n__tune_k8__ 1\n"
    print(f'    {{ c"", {mask(default):#x}, {fas_string(old_names)} }},')
    base_names = set(default) | {"__k8", "__k8__", "__tune_k8__"}
    for cpu, m in sorted(cpu_macros.items()):
        extras = "".join(f"{name} {value}\n" for name, value in sorted(m.items())
                         if name not in base_names and name not in controlled and name not in half)
        if cpu == "k8":
            extras += old_names
        print(f'    {{ c"{cpu}", {mask(m):#x}, {fas_string(extras)} }},')
    print("}")

if __name__ == "__main__":
    generate()
