# generates test/fas_fir/c/c23.fir and c23.c: the Fir lowering of C23 library
# features that are plain code (SPEC §11, "C23"), checked against clang and
# glibc on edge and random values:
#   <stdckdint.h> ckd_add/ckd_sub/ckd_mul with operand and result types of
#     any signedness and width: both operands extend to i129, which holds
#     every exact result, and the result type must hold the value (truncate,
#     extend back, compare);
#   <stdbit.h>: every function family at 8, 16, 32 and 64 bits, through
#     clz/ctz/popcnt (bit_ceil only where the result is representable; C23
#     leaves the rest unspecified).
#   python3 test/fas_fir/c/gen_c23.py   (from the repository root)
T = {  # name: (bits, signed, C type)
 's8': (8, True, 'signed char'), 'u8': (8, False, 'unsigned char'),
 's16': (16, True, 'short'), 'u16': (16, False, 'unsigned short'),
 's32': (32, True, 'int'), 'u32': (32, False, 'unsigned'),
 's64': (64, True, 'long'), 'u64': (64, False, 'unsigned long')}
# (a, b, result): same types, mixed signedness, narrowing and widening results
TRIPLES = [('s32','s32','s32'), ('u32','u32','u32'), ('s64','u64','s64'), ('u64','s64','u64'),
           ('s64','s64','s8'), ('u8','s16','u16'), ('s32','u64','s16'), ('u64','u64','s64'),
           ('s8','s8','u64'), ('s64','s64','u32'), ('u16','u16','s8'), ('s16','u32','u8')]
fir = ['; generated by gen_c23.py: C23 <stdckdint.h> and <stdbit.h> lowerings, checked by c23.c against clang and glibc',
       'triple "x86_64-unknown-linux-gnu"']
c = ['#include <stdio.h>\n#include <stdbit.h>\n#include <stdckdint.h>\n#include <stdbool.h>\n'
     'static unsigned long long st = 88172645463325252ULL;\n'
     'static unsigned long long rnd(void) { st ^= st << 13; st ^= st >> 7; st ^= st << 17; return st; }\n'
     '/* edge values first, then random ones of random magnitude */\n'
     'static unsigned long long val(int i) {\n'
     '  static const unsigned long long e[] = { 0, 1, 2, 3, ~0ULL, ~0ULL - 1, 1ULL << 63, (1ULL << 63) - 1, 0x80, 0x7f, 0xff, 0x8000, 0x7fff, 0xffff, 0x80000000, 0x7fffffff, 0xffffffff, 0x100000000 };\n'
     '  if (i < (int)(sizeof e / sizeof e[0])) return e[i];\n'
     '  unsigned long long r = rnd(); return rnd() % 2 ? r >> (rnd() % 64) : r;\n}\n'
     'static int fails;\n']
main = ['int main(void) {']
OPS = {'add': ('add', 'ckd_add'), 'sub': ('sub', 'ckd_sub'), 'mul': ('mul', 'ckd_mul')}
for op, (fop, cm) in OPS.items():
    for ta, tb, tr in TRIPLES:
        (wa, sa, ca), (wb, sb, cb), (wr, sr, cr) = T[ta], T[tb], T[tr]
        name = f'ckd_{op}_{ta}_{tb}_{tr}'
        ext = lambda s: 'sext' if s else 'zext'
        fir.append(f'''func @{name} (ptr, i{wa}, i{wb}) -> (i8) global {{
^e(%r: ptr, %a: i{wa}, %b: i{wb}):
  %ea = {ext(sa)} i129 %a
  %eb = {ext(sb)} i129 %b
  %v = {fop} i129 %ea, %eb
  %t = trunc i{wr} %v
  %back = {ext(sr)} i129 %t
  %fits = icmp eq i1 %back, %v
  store %t, %r, align {wr // 8}
  %o = xor i1 %fits, i1 1
  %ow = zext i8 %o
  ret %ow
}}''')
        c.append(f'unsigned char {name}({cr} *, {ca}, {cb});')
        c.append(f'''static void t_{name}(void) {{
  for (int i = 0; i < 3000; i++) {{
    {ca} a = ({ca})val(i); {cb} b = ({cb})val(i < 18 ? 17 - i : i + 7);
    if (i % 5 == 1) b = ({cb})val(i / 5);
    {cr} x = 0, y = 0;
    bool o1 = {cm}(&x, a, b);
    bool o2 = {name}(&y, a, b);
    if (o1 != o2 || x != y) {{ if (fails++ < 20) printf("FAIL {name} %lld %lld: c %d %lld fir %d %lld\\n", (long long)a, (long long)b, o1, (long long)x, o2, (long long)y); }}
  }}
}}''')
        main.append(f'  t_{name}();')
# stdbit, with w the width and N the C suffix
SB = {8: 'uc', 16: 'us', 32: 'ui', 64: 'ul'}
CT = {8: 'unsigned char', 16: 'unsigned short', 32: 'unsigned', 64: 'unsigned long'}
def sb(fn, w):
    """Fir body computing %r (i32 for counts and bools, i{w} for bit_floor/ceil) from %x : i{w}"""
    t = f'i{w}'
    nx = [f'%nx = xor {t} %x, {t} -1']
    z = [f'%z = icmp eq i1 %x, {t} 0']
    ones = [f'%ones = icmp eq i1 %x, {t} -1']
    r32 = lambda v: [f'%r = zext i32 {v}'] if w < 32 else ([f'%r = trunc i32 {v}'] if w > 32 else [f'%r = add i32 {v}, i32 0'])
    if fn == 'leading_zeros': return [f'%c = clz {t} %x'] + r32('%c')
    if fn == 'leading_ones': return nx + [f'%c = clz {t} %nx'] + r32('%c')
    if fn == 'trailing_zeros': return [f'%c = ctz {t} %x'] + r32('%c')
    if fn == 'trailing_ones': return nx + [f'%c = ctz {t} %nx'] + r32('%c')
    if fn == 'first_leading_zero': return nx + ones + [f'%c = clz {t} %nx', f'%c1 = add {t} %c, {t} 1', f'%v = select {t} %ones, {t} 0, %c1'] + r32('%v')
    if fn == 'first_leading_one': return z + [f'%c = clz {t} %x', f'%c1 = add {t} %c, {t} 1', f'%v = select {t} %z, {t} 0, %c1'] + r32('%v')
    if fn == 'first_trailing_zero': return nx + ones + [f'%c = ctz {t} %nx', f'%c1 = add {t} %c, {t} 1', f'%v = select {t} %ones, {t} 0, %c1'] + r32('%v')
    if fn == 'first_trailing_one': return z + [f'%c = ctz {t} %x', f'%c1 = add {t} %c, {t} 1', f'%v = select {t} %z, {t} 0, %c1'] + r32('%v')
    if fn == 'count_zeros': return [f'%c = popcnt {t} %x', f'%v = sub {t} {t} {w}, %c'] + r32('%v')
    if fn == 'count_ones': return [f'%c = popcnt {t} %x'] + r32('%c')
    if fn == 'has_single_bit': return [f'%c = popcnt {t} %x', f'%b = icmp eq i1 %c, {t} 1', '%r = zext i32 %b']
    if fn == 'bit_width': return [f'%c = clz {t} %x', f'%v = sub {t} {t} {w}, %c'] + r32('%v')
    if fn == 'bit_floor': return z + [f'%c = clz {t} %x', f'%s = sub {t} {t} {w - 1}, %c', f'%p = shl {t} {t} 1, %s', f'%r = select {t} %z, {t} 0, %p']
    if fn == 'bit_ceil': return [f'%small = icmp ule i1 %x, {t} 1', f'%m = sub {t} %x, {t} 1', f'%c = clz {t} %m', f'%s = sub {t} {t} {w}, %c', f'%p = shl {t} {t} 1, %s', f'%r = select {t} %small, {t} 1, %p']
FNS = ['leading_zeros', 'leading_ones', 'trailing_zeros', 'trailing_ones', 'first_leading_zero', 'first_leading_one',
       'first_trailing_zero', 'first_trailing_one', 'count_zeros', 'count_ones', 'has_single_bit', 'bit_width', 'bit_floor', 'bit_ceil']
for w, sfx in SB.items():
    for fn in FNS:
        rt = f'i{w}' if fn in ('bit_floor', 'bit_ceil') else 'i32'
        crt = CT[w] if rt != 'i32' else 'unsigned'
        fir.append(f'func @sb_{fn}_{sfx} (i{w}) -> ({rt}) global {{\n^e(%x: i{w}):\n  ' + '\n  '.join(sb(fn, w)) + '\n  ret %r\n}')
        c.append(f'{crt} sb_{fn}_{sfx}({CT[w]});')
        guard = f'if (x > ({CT[w]})1 << {w - 1}) continue;' if fn == 'bit_ceil' else ''
        c.append(f'''static void t_sb_{fn}_{sfx}(void) {{
  for (int i = 0; i < 3000; i++) {{
    {CT[w]} x = ({CT[w]})val(i);
    {guard}
    unsigned long long a = stdc_{fn}_{sfx}(x), b = sb_{fn}_{sfx}(x);
    if (a != b) {{ if (fails++ < 20) printf("FAIL stdc_{fn}_{sfx}(%#llx): c %llu fir %llu\\n", (unsigned long long)x, a, b); }}
  }}
}}''')
        main.append(f'  t_sb_{fn}_{sfx}();')
main.append('  if (fails) printf("fails=%d\\n", fails);\n  return fails != 0;\n}')
open('test/fas_fir/c/c23.fir', 'w').write('\n'.join(fir) + '\n')
open('test/fas_fir/c/c23.c', 'w').write('\n'.join(c + main) + '\n')
