# generates test/fas_fir/c/fenv.fir and fenv.c: float operations under the
# dynamic floating-point environment. Each op runs in all four rounding
# modes and its result and IEEE flags (fetestexcept) must match C's.
#   python3 test/fas_fir/c/gen_fenv.py   (from the repository root)
# The C side builds with FENV_ACCESS and calls each reference through a
# noinline function, so nothing is folded at compile time. Where C cannot be
# the reference:
#   _BitInt(200) -> float: clang has no strictfp lowering for it, so the
#     reference is the __int128 v >> 64 with a sticky bit, scaled by 2^64
#     (same rounding: the dropped bits are below half an ulp and nonzero);
#   double -> unsigned __int128 follows Annex F instead (C leaves values out
#     of range undefined, libgcc raises a spurious inexact): an integral
#     value in range is exact with no flags, a fraction truncates (inexact
#     allowed), out of range raises exactly invalid (value unspecified).
# The tail checks three-operand fma at f32/f64/f80 on random and edge
# operands (overflow, underflow, cancellation, the tininess boundary
# just below 2^-16382) against the C library's fmaf/fma/fmal.
ops = [
 ('div32','f32','f32',['%r = fdiv f32 %a, %b'],'float','float','a/b'),
 ('div64','f64','f64',['%r = fdiv f64 %a, %b'],'double','double','a/b'),
 ('div80','f80','f80',['%r = fdiv f80 %a, %b'],'long double','long double','a/b'),
 ('add64','f64','f64',['%r = fadd f64 %a, %b'],'double','double','a+b'),
 ('mul80','f80','f80',['%r = fmul f80 %a, %b'],'long double','long double','a*b'),
 ('div16','f16','f16',['%r = fdiv f16 %a, %b'],'_Float16','_Float16','a/b'),
 ('add16','f16','f16',['%r = fadd f16 %a, %b'],'_Float16','_Float16','a+b'),
 ('sqrt64','f64','f64',['%r = sqrt f64 %a'],'double','double','__builtin_sqrt(a)'),
 ('sqrt80','f80','f80',['%r = sqrt f80 %a'],'long double','long double','__builtin_sqrtl(a)'),
 ('fma64','f64','f64',['%r = fma f64 %a, %b, %a'],'double','double','__builtin_fma(a,b,a)'),
 ('fma80','f80','f80',['%r = fma f80 %a, %b, %a'],'long double','long double','__builtin_fmal(a,b,a)'),
 ('fmah','f16','f16',['%r = fma f16 %a, %b, %a'],'_Float16','_Float16','(_Float16)__builtin_fmaf(a,b,a)'),
 ('tr6432','f64','f32',['%r = fptrunc f32 %a'],'double','float','(float)a'),
 ('tr8064','f80','f64',['%r = fptrunc f64 %a'],'long double','double','(double)a'),
 ('tr6416','f64','f16',['%r = fptrunc f16 %a'],'double','_Float16','(_Float16)a'),
 ('tr3216','f32','f16',['%r = fptrunc f16 %a'],'float','_Float16','(_Float16)a'),
 ('si64f32','i64','f32',['%r = sitofp f32 %a'],'long','float','(float)a'),
 ('si64f64','i64','f64',['%r = sitofp f64 %a'],'long','double','(double)a'),
 ('ui64f64','i64','f64',['%r = uitofp f64 %a'],'unsigned long','double','(double)a'),
 ('ui64f32','i64','f32',['%r = uitofp f32 %a'],'unsigned long','float','(float)a'),
 ('si128f64','i128','f64',['%r = sitofp f64 %a'],'__int128','double','(double)a'),
 ('ui128f32','i128','f32',['%r = uitofp f32 %a'],'unsigned __int128','float','(float)a'),
 ('si128f80','i128','f80',['%r = sitofp f80 %a'],'__int128','long double','(long double)a'),
 ('si64f16','i64','f16',['%r = sitofp f16 %a'],'long','_Float16','(_Float16)a'),
 ('fp64si','f64','i64',['%r = fptosi i64 %a'],'double','long','(long)a'),
 ('fp64ui','f64','i64',['%r = fptoui i64 %a'],'double','unsigned long','(unsigned long)a'),
 ('fp32ui','f32','i64',['%r = fptoui i64 %a'],'float','unsigned long','(unsigned long)a'),
 ('fp80ui','f80','i64',['%r = fptoui i64 %a'],'long double','unsigned long','(unsigned long)a'),
 ('si200f64','i200','f64',['%r = sitofp f64 %a'],'__int128','double','(double)(a>>64|((a&0xffffffffffffffff)!=0))*0x1p64'),
 ('ui200f32','i200','f32',['%r = uitofp f32 %a'],'unsigned __int128','float','(float)(a>>64|((a&0xffffffffffffffff)!=0))*0x1p64f'),
]
# the i200 ops take a pointer to the value (the C side passes a 200-bit
# little-endian buffer built from the __int128); True: signed
wide = {'si200f64': True, 'ui200f32': False}
fir=['; generated by gen_fenv.py: float ops under the dynamic floating-point environment, checked by fenv.c',
     '; llvm: skip FENV semantics are native-only (the LLVM path emits no strictfp operations)',
     'triple "x86_64-unknown-linux-gnu"']
c=['''#include <fenv.h>
#include <stdio.h>
#include <string.h>
#include <math.h>
#pragma STDC FENV_ACCESS ON
static int fails;
static const int modes[4]={FE_TONEAREST,FE_UPWARD,FE_DOWNWARD,FE_TOWARDZERO};
/* the 200-bit two's complement of v (sign-extended) */
static void to200(unsigned char *p, __int128 v) { memset(p, v < 0 ? 0xff : 0, 32); memcpy(p, &v, 16); }
''']
for name,ta,tr,body,ca,cr,expr in ops:
    binary = '%b' in body[0]
    if name in wide:
        fir.append(f'func @fir_{name} (ptr) -> ({tr}) global noinline {{\n^e(%p: ptr):\n  %a = load i200 %p, align 8\n  '+'\n  '.join(body)+'\n  ret %r\n}')
        c.append(f'{cr} fir_{name}(const void *);')
        call = 'fir_%s(buf)' % name
        pre = 'unsigned char buf[32]; to200(buf, (__int128)a);'
    else:
        sig = f'({ta}, {ta})' if binary else f'({ta})'
        heads = f'%a: {ta}, %b: {ta}' if binary else f'%a: {ta}'
        fir.append(f'func @fir_{name} {sig} -> ({tr}) global noinline {{\n^e({heads}):\n  '+'\n  '.join(body)+'\n  ret %r\n}')
        cs = f'{ca}, {ca}' if binary else ca
        c.append(f'{cr} fir_{name}({cs});')
        call = f"fir_{name}({'a, b' if binary else 'a'})"
        pre = ''
    c.append(f'__attribute__((noinline)) static {cr} c_{name}({ca} a, {ca} b) {{ (void)b; return {expr}; }}')
    size = '10' if cr == 'long double' else 'sizeof xx'
    c.append(f'''static void t_{name}({ca} a, {ca} b) {{
  {pre}
  for (int m = 0; m < 4; m++) {{
    fesetround(modes[m]); feclearexcept(FE_ALL_EXCEPT);
    volatile {cr} x = c_{name}(a, b); int fx = fetestexcept(FE_ALL_EXCEPT);
    feclearexcept(FE_ALL_EXCEPT);
    volatile {cr} y = {call}; int fy = fetestexcept(FE_ALL_EXCEPT);
    fesetround(FE_TONEAREST);
    {cr} xx = x, yy = y;
    if (memcmp(&xx, &yy, {size}) != 0 && !(xx != xx && yy != yy)) {{ fails++; printf("FAIL value {name} mode %d\\n", m); }}
    if (fx != fy) {{ fails++; printf("FAIL flags {name} mode %d: c %#x fir %#x\\n", m, fx, fy); }}
  }}
}}''')
# double -> unsigned __int128 by Annex F
fir.append('func @fir_fp64ui128 (f64) -> (i128) global noinline {\n^e(%a: f64):\n  %r = fptoui i128 %a\n  ret %r\n}')
c.append('''unsigned __int128 fir_fp64ui128(double);
static void t_fp64ui128(double a) {
  int in = a > -1.0 && a < 0x1p128;
  for (int m = 0; m < 4; m++) {
    fesetround(modes[m]); feclearexcept(FE_ALL_EXCEPT);
    volatile unsigned __int128 y = fir_fp64ui128(a); int fy = fetestexcept(FE_ALL_EXCEPT);
    fesetround(FE_TONEAREST);
    if (!in) {
      if (fy != FE_INVALID) { fails++; printf("FAIL flags fp64ui128 %a mode %d: %#x, want invalid\\n", a, m, fy); }
      continue;
    }
    double t = a < 0 ? 0.0 : a - fmod(a, 1.0);
    unsigned __int128 want;
    if (t >= 0x1p64) want = (unsigned __int128)(unsigned long)(t * 0x1p-64) << 64 | (unsigned long)fmod(t, 0x1p64);
    else want = (unsigned long)t;
    int allowed = t == a ? 0 : FE_INEXACT;
    if (y != want) { fails++; printf("FAIL value fp64ui128 %a mode %d\\n", a, m); }
    if (fy & ~allowed) { fails++; printf("FAIL flags fp64ui128 %a mode %d: %#x\\n", a, m, fy); }
  }
}''')
vals = {'f':['1.0f','3.0f','0.1f','-7.0f','1e30f','0.0f'],
        'd':['1.0','3.0','0.1','-7.0','1e300','0.0','0x1.fffffffffffffp+60','-0x1.8p+70','0x1.8p+100','0x1.0000000000001p+65','-0.5'],
        'i':['1','3','-7','0x7fffffffffffffffL','123456789123456789L'],
        'h':['(_Float16)1.0','(_Float16)3.0','(_Float16)0.1','(_Float16)-7.0']}
i128x = ['((__int128)0x7fffffffffffffffL<<40)+12345','-((__int128)0x7fffffffffffffffL<<40)-12345']
# 200-bit values held in an __int128 (the Fir side sees them sign-extended)
i200 = ['(__int128)1 << 126', '((__int128)0x7fffffffffffffffL<<62)+1', '((__int128)0x1fffffffffffffL<<70)+((__int128)1<<16)']
def vs(name, t):
    if name in wide: return i200 + (['-((__int128)0x7fffffffffffffffL<<60)-12345', '-((__int128)1 << 126)'] if wide[name] else [])
    if t == 'float': return vals['f']
    if t in ('double','long double'): return vals['d']
    if t == '_Float16': return vals['h']
    return vals['i'] + (i128x if '128' in t else [])
main=['''
/* three-operand fma on random and edge operands, against the C library */
float fir_fma32(float, float, float);
double fir_fma64x(double, double, double);
long double fir_fma80x(long double, long double, long double);
static unsigned long long st = 88172645463325252ULL;
static unsigned long long rnd(void) { st ^= st << 13; st ^= st >> 7; st ^= st << 17; return st; }
static long double mk80(unsigned long long m, int e, int s) {
  long double x; unsigned char b[16] = {0}; unsigned short h = (e & 0x7fff) | (s << 15);
  memcpy(b, &m, 8); memcpy(b + 8, &h, 2); memcpy(&x, b, 16); return x;
}
/* random significand bits, a run of ones or a power of two plus a little */
static unsigned long long sig(void) {
  switch (rnd() % 4) { case 0: return ~0ULL << (rnd() % 64); case 1: return 1ULL << 63 | rnd() % 4; default: return rnd(); }
}
/* operands near the bottom, near the top, near 1, subnormal or anywhere */
static long double r80(void) {
  int e;
  switch (rnd() % 5) {
  case 0: e = 1 + rnd() % 40; break;
  case 1: e = 0x7ffe - rnd() % 40; break;
  case 2: e = 0x3fff + (int)(rnd() % 100) - 50; break;
  case 3: return mk80(sig() >> (1 + rnd() % 63), 0, rnd() & 1);
  default: e = 1 + rnd() % 0x7ffd;
  }
  return mk80(sig() | 1ULL << 63, e, rnd() & 1);
}
static double r64(void) {
  unsigned long long m = sig() >> 12, e;
  switch (rnd() % 5) {
  case 0: e = rnd() % 40; break;
  case 1: e = 0x7fe - rnd() % 40; break;
  case 2: e = 0x3ff + rnd() % 100 - 50; break;
  case 3: e = 0; break;
  default: e = rnd() % 0x7ff;
  }
  unsigned long long b = (rnd() & 1) << 63 | e << 52 | (m & 0xfffffffffffffULL);
  double x; memcpy(&x, &b, 8); return x;
}
static float r32(void) {
  unsigned int m = sig() >> 41, e;
  switch (rnd() % 5) {
  case 0: e = rnd() % 20; break;
  case 1: e = 0xfe - rnd() % 20; break;
  case 2: e = 0x7f + rnd() % 40 - 20; break;
  case 3: e = 0; break;
  default: e = rnd() % 0xff;
  }
  unsigned int b = (unsigned)(rnd() & 1) << 31 | e << 23 | (m & 0x7fffff);
  float x; memcpy(&x, &b, 4); return x;
}
#define CHECK(T, n, cf, ff, x, y, z) do { \\
  for (int m = 0; m < 4; m++) { \\
    fesetround(modes[m]); feclearexcept(FE_ALL_EXCEPT); \\
    volatile T a = cf(x, y, z); int fa = fetestexcept(FE_ALL_EXCEPT); \\
    feclearexcept(FE_ALL_EXCEPT); \\
    volatile T b = ff(x, y, z); int fb = fetestexcept(FE_ALL_EXCEPT); \\
    fesetround(FE_TONEAREST); \\
    T aa = a, bb = b; \\
    if ((memcmp(&aa, &bb, n) != 0 && !(aa != aa && bb != bb)) || fa != fb) { \\
      if (fails++ < 20) printf("FAIL " #ff " mode %d: %La %La %La: c %La %#x fir %La %#x\\n", m, \\
        (long double)x, (long double)y, (long double)z, (long double)aa, fa, (long double)bb, fb); } \\
  } } while (0)
__attribute__((noinline)) static float c_fmaf(float x, float y, float z) { return fmaf(x, y, z); }
__attribute__((noinline)) static double c_fma(double x, double y, double z) { return fma(x, y, z); }
__attribute__((noinline)) static long double c_fmal(long double x, long double y, long double z) { return fmal(x, y, z); }
static void t_fma3(void) {
  for (int i = 0; i < 20000; i++) {
    long double x = r80(), y = r80(), z;
    switch (rnd() % 4) {
    case 0: { volatile long double p = x * y; z = -p; break; }
    case 1: z = mk80(rnd() | 1ULL << 63, 1 + rnd() % 3, rnd() & 1); break;
    default: z = r80();
    }
    CHECK(long double, 10, c_fmal, fir_fma80x, x, y, z);
    /* just below 2^-16382: tiny or not depending on rounding at 64 bits */
    x = mk80(~0ULL - rnd() % 4, 0x3fff - rnd() % 3, rnd() & 1);
    y = mk80(1ULL << 63 | rnd() % 8, 1 + rnd() % 3, rnd() & 1);
    z = mk80(rnd() % 16, 0, rnd() & 1);
    CHECK(long double, 10, c_fmal, fir_fma80x, x, y, z);
    double dx = r64(), dy = r64(), dz;
    if (rnd() % 4 == 0) { volatile double p = dx * dy; dz = -p; } else dz = r64();
    CHECK(double, 8, c_fma, fir_fma64x, dx, dy, dz);
    float fx = r32(), fy = r32(), fz;
    if (rnd() % 4 == 0) { volatile float p = fx * fy; fz = -p; } else fz = r32();
    CHECK(float, 4, c_fmaf, fir_fma32, fx, fy, fz);
  }
}
int main(void) {''']
for t, n in [('f32','fma32'), ('f64','fma64x'), ('f80','fma80x')]:
    fir.append(f'func @fir_{n} ({t}, {t}, {t}) -> ({t}) global noinline {{\n^e(%a: {t}, %b: {t}, %c: {t}):\n  %r = fma {t} %a, %b, %c\n  ret %r\n}}')
for name,ta,tr,body,ca,cr,expr in ops:
    for a in vs(name, ca):
        for b in vs(name, ca)[:4]:
            main.append(f'  t_{name}({a}, {b});')
for a in vals['d']:
    main.append(f'  t_fp64ui128({a});')
main.append('  t_fma3();\n  if (fails) printf("fails=%d\\n", fails);\n  return fails != 0;\n}')
open('test/fas_fir/c/fenv.fir','w').write('\n'.join(fir)+'\n')
open('test/fas_fir/c/fenv.c','w').write('\n'.join(c+main)+'\n')
