# generates test/fas_fir/c/huge.fir and huge.c: _BitInt widths far beyond
# gen_wide.py's (1500 and 4096 bits; Fir allows up to 8388608). Division,
# shifts, bit counts and int-to-double are checked against clang's
# _BitInt(N) on special and random values.
#   python3 test/fas_fir/c/gen_huge.py   (from the repository root)
# Natively 8191 bits pass too (and i65536 compiles in under a second); the
# LLVM path is slow at these widths (about 45 s for 1500+4096+8191, and
# i65536 did not finish in 10 minutes), so the suite keeps two widths.
# int-to-double is compared only when the value fits a double: past
# 2^1024 C leaves it undefined (we give +-inf, clang gives garbage).
import sys
W=[1500, 4096]
BIN=['add','sub','mul','udiv','urem','sdiv','srem','shl','lshr','ashr','umin','smax']
fir=['; generated by gen_huge.py: _BitInt widths far past the wide suite, checked by huge.c against clang', 'triple "x86_64-unknown-linux-gnu"']; c=['#include <stdio.h>\n#include <string.h>\n#include <stdlib.h>\nstatic unsigned long long st=88172645463325252ULL;\nstatic unsigned long long rnd(void){st^=st<<13;st^=st>>7;st^=st<<17;return st;}\nint fails=0;\n']
cop={'add':'a+b','sub':'a-b','mul':'a*b','udiv':'a/b','urem':'a%b','sdiv':'sa/sb','srem':'sa%sb','shl':'a<<(b%N)','lshr':'a>>(b%N)','ashr':'sa>>(b%N)','umin':'a<b?a:b','smax':'sa>sb?sa:sb'}
for n in W:
    t=f'i{n}'
    for op in BIN:
        body=[f'%a = load {t} %pa, align 8',f'%b = load {t} %pb, align 8']
        if op in('shl','lshr','ashr'):
            body+=[f'%bm = urem {t} %b, {t} {n}',f'%v = {op} {t} %a, %bm']
        else: body+=[f'%v = {op} {t} %a, %b']
        fir.append(f'func @f_{op}_{n} (ptr, ptr, ptr) -> () global {{\n^e(%r: ptr, %pa: ptr, %pb: ptr):\n  '+'\n  '.join(body+['store %v, %r, align 8','ret'])+'\n}')
        c.append(f'void f_{op}_{n}(void*,void*,void*);')
    for op in ['ctz','clz','popcnt']:
        fir.append(f'func @f_{op}_{n} (ptr, ptr) -> () global {{\n^e(%r: ptr, %pa: ptr):\n  %a = load {t} %pa, align 8\n  %v = {op} {t} %a\n  store %v, %r, align 8\n  ret\n}}')
        c.append(f'void f_{op}_{n}(void*,void*);')
    fir.append(f'func @f_sitofp_{n} (ptr) -> (f64) global {{\n^e(%pa: ptr):\n  %a = load {t} %pa, align 8\n  %v = sitofp f64 %a\n  ret %v\n}}')
    c.append(f'double f_sitofp_{n}(void*);')
    U=f'unsigned _BitInt({n})'; S=f'_BitInt({n})'
    c.append(f'''static void fill_{n}({U}*x,int k){{ unsigned char*p=(unsigned char*)x; for(size_t i=0;i<sizeof *x;i++)p[i]=rnd(); *x=*x;
  if(k==0)*x=0; else if(k==1)*x=1; else if(k==2)*x=({U})-1; else if(k==3)*x=(({U})-1)>>1; else if(k==4)*x=~((({U})-1)>>1); else if(k==5)*x>>= (rnd()%{n}); else if(k==6)*x=rnd(); }}
static void t_{n}(void){{ enum{{N={n}}};
 for(int it=0;it<400;it++){{ {U} a,b,r,e; fill_{n}(&a,it%9); fill_{n}(&b,(it/9)%9); {S} sa=({S})a, sb=({S})b; (void)sa;(void)sb;''')
    for op in BIN:
        guard={'udiv':'b!=0','urem':'b!=0','sdiv':f'sb!=0 && !(sa==({S})~((({U})-1)>>1) && sb==-1)','srem':f'sb!=0 && !(sa==({S})~((({U})-1)>>1) && sb==-1)'}.get(op,'1')
        c.append(f'  if({guard}){{ memset(&r,0xa5,sizeof r); f_{op}_{n}(&r,&a,&b); e=({U})({cop[op]}); if(memcmp(&r,&e,({n}+7)/8)){{ if(fails++<100000)printf("FAIL {op} {n} it=%d\\n",it);}} }}')
    for op,ex in [('ctz',f'a?__builtin_ctzg(a):{n}'),('clz',f'a?__builtin_clzg(a):{n}'),('popcnt','__builtin_popcountg(a)')]:
        c.append(f'  {{ f_{op}_{n}(&r,&a); e=({U})({ex}); if(memcmp(&r,&e,({n}+7)/8)){{ if(fails++<100000)printf("FAIL {op} {n} it=%d\\n",it);}} }}')
    c.append(f'  {{ {U} m = sa<0 ? ({U})-a : a; int bl = m ? {n}-__builtin_clzg(m) : 0; double d=f_sitofp_{n}(&a), x=(double)sa; if(bl<=1023 && d!=x){{ if(fails++<100000)printf("FAIL sitofp {n} it=%d %g %g\\n",it,d,x);}} }}')
    c.append('}}')
c.append('int main(void){'+''.join(f't_{n}();' for n in W)+'printf("fails=%d\\n",fails);return fails!=0;}')
open('test/fas_fir/c/huge.fir','w').write('\n'.join(fir)+'\n'); open('test/fas_fir/c/huge.c','w').write('\n'.join(c)+'\n')
